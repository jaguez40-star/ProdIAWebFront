  SELECT 
    CAUSAS_VPU_AGRUPADAS,
    CAUSE_NIVEL4,    
    CAUSE_NIVEL5,
    ROUND(BOPD_2023, 2) AS BOPD_2023,
    ROUND(BOPD_2024, 2) AS BOPD_2024,
