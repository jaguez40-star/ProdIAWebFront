    x.CAUSE_NIVEL2='Facilidades' AND
    x.CAUSAS_VPU_AGRUPADAS='Operacionales'
  GROUP BY 
    x.CAUSAS_VPU_AGRUPADAS,
    x.CAUSE_NIVEL4,
    x.CAUSE_NIVEL5
),
total_general AS (
  SELECT SUM(BOPD_2023 + BOPD_2024 + BOPD_2025) AS TOTAL FROM datos
),
porcentajes AS (
  SELECT 
    d.CAUSAS_VPU_AGRUPADAS,
    d.CAUSE_NIVEL4,    
    d.CAUSE_NIVEL5,
    d.BOPD_2023,
    d.BOPD_2024,
    d.BOPD_2025,
    d.BOPD_GAA,
    d.BOPD_GLH,
    d.BOPD_GCT,
    d.BOPD_GGS,
    d.BOPD_GOR,
    d.BOPD_GPA,
    d.BOPD_GRM,
    d.BOPD_GTA,
CASE
      WHEN (d.BOPD_2025 - d.BOPD_2024) > 10 THEN 1
      WHEN (d.BOPD_2025 - d.BOPD_2024) < 0 THEN 3
      ELSE 2
