DROP VIEW IF EXISTS DIF_YEAR_GERENCIA;
CREATE VIEW DIF_YEAR_GERENCIA AS SELECT 
  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) AS AÑO,  
  x.VICE_HOM,
  SUM(x.BOPD) AS DIF_BOPD
FROM 
  DIM_DIFERIDAS x
WHERE
CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) IN (2023,2024)
GROUP BY 
  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER),    
  x.VICE_HOM
UNION
SELECT 
  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) AS AÑO,  
  x.VICE_HOM,
  (SUM(x.ACEITE_PERDIDO)/181) AS DIF_BOPD
FROM 
  DIM_DIFERIDAS x
WHERE
CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) IN (2025)
GROUP BY 
  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER),    
  x.VICE_HOM;

DROP VIEW IF EXISTS GRAF_DIF_03;
CREATE VIEW GRAF_DIF_03 AS SELECT 
  '2023' AS AÑO,
  x.VICE_HOM,
  SUM(x.BOPD) AS DIF_BOPD,
  ROUND(
    SUM(x.BOPD) * 1.0 / (
      SELECT SUM(BOPD)
      FROM DIM_DIFERIDAS
      WHERE CAST(SUBSTR(EVENT_DATE, 1, 4) AS INTEGER) = 2023
    ), 
  4) AS PORCENTAJE
FROM 
  DIM_DIFERIDAS x
WHERE 
  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2023
GROUP BY 
  x.VICE_HOM
UNION
SELECT 
  '2024' AS AÑO,
  x.VICE_HOM,
  SUM(x.BOPD) AS DIF_BOPD,
  ROUND(
    SUM(x.BOPD) * 1.0 / (
      SELECT SUM(BOPD)
      FROM DIM_DIFERIDAS
      WHERE CAST(SUBSTR(EVENT_DATE, 1, 4) AS INTEGER) = 2024
    ), 
  4) AS PORCENTAJE
FROM 
  DIM_DIFERIDAS x
WHERE 
  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2024
GROUP BY 
  x.VICE_HOM
UNION
SELECT 
  '2025' AS AÑO,
  x.VICE_HOM,
  (SUM(x.ACEITE_PERDIDO)/212) AS DIF_BOPD,
  ROUND(
    (SUM(x.ACEITE_PERDIDO)/212) * 1.0 / (
      SELECT (SUM(DIM_DIFERIDAS.ACEITE_PERDIDO)/212)
      FROM DIM_DIFERIDAS
      WHERE CAST(SUBSTR(EVENT_DATE, 1, 4) AS INTEGER) = 2025
    ), 
  4) AS PORCENTAJE
FROM 
  DIM_DIFERIDAS x
WHERE 
  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025
GROUP BY 
  x.VICE_HOM;

