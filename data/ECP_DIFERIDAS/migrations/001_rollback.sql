    CAUSAS_VPU_AGRUPADAS,
    CAUSE_NIVEL4,    
    'otros' AS CAUSE_NIVEL5,
    ROUND(SUM(BOPD_2023), 2),
    ROUND(SUM(BOPD_2024), 2),
