    ROUND(BOPD_GCT, 2) AS BOPD_GCT,
    ROUND(BOPD_GGS, 2) AS BOPD_GGS,
    ROUND(BOPD_GOR, 2) AS BOPD_GOR,
    ROUND(BOPD_GPA, 2) AS BOPD_GPA,
