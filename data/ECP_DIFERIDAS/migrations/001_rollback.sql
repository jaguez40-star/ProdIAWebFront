    ROUND(SUM(BOPD_GOR), 2),
    ROUND(SUM(BOPD_GPA), 2),
    ROUND(SUM(BOPD_GRM), 2),
    ROUND(SUM(BOPD_GTA), 2),    
    2 AS DIFERENCIA,
    ROUND(SUM(PORCENTAJE), 2)
  FROM porcentajes
  --WHERE PORCENTAJE < 0.0001
)
