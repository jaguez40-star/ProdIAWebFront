-- 002_pareto_otros_duplicado.sql
-- ECP_DIFERIDAS · Corrige la DUPLICACION EXACTA (2,000x) en las vistas Pareto/Nodo.
--
-- PROBLEMA
--   El patron "detalle + bucket otros" estaba roto en 4 vistas:
--       SELECT ... FROM porcentajes WHERE PORCENTAJE >= 0      <- toma TODAS las filas
--       UNION ALL
--       SELECT ..., 'otros' ... FROM porcentajes
--       --WHERE PORCENTAJE < 0.0001                            <- FILTRO COMENTADO
--   El detalle trae todo y 'otros' vuelve a sumar todo -> cada fila se cuenta DOS VECES.
--   Verificado: PARETOS_N4_N5 implicaba 8.834.112 bbl de aceite 2025 cuando el real de su
--   alcance (CAUSAS_VPU_AGRUPADAS='Operacionales') es 4.417.059 -> ratio exacto 2,000x.
--
-- SOLUCION
--   Replicar el patron de las vistas HERMANAS QUE YA ESTAN SANAS (PARETOS_N4_OPERACIONAL y
--   PARETOS_N4_ENTORNO, ambas con ratio 1,000x): detalle >= 0.01 / otros < 0.01. Los dos
--   filtros son complementarios y disjuntos -> sin duplicar ni perder filas.
--   Ojo: PORCENTAJE = ROUND(...,2), asi que "< 0.01" = las causas que redondean a 0%.
--
-- EFECTO ESPERADO: las 4 vistas pasan de 2,000x a 1,000x. Las 3 sanas NO se tocan.
-- IDEMPOTENTE (DROP VIEW IF EXISTS + CREATE VIEW). Rollback: 002_rollback.sql

BEGIN;

-- PARETOS_N4_N5: detalle x1, otros x1
DROP VIEW IF EXISTS PARETOS_N4_N5;
CREATE VIEW PARETOS_N4_N5 AS WITH datos AS (
  SELECT 
    x.CAUSAS_VPU_AGRUPADAS,
    x.CAUSE_NIVEL4,
    x.CAUSE_NIVEL5,
    SUM(CASE WHEN CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2023 THEN x.BOPD ELSE 0 END) AS BOPD_2023,
    SUM(CASE WHEN CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2024 THEN x.BOPD ELSE 0 END) AS BOPD_2024,
    SUM(CASE WHEN CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_2025,
    SUM(CASE WHEN x.VICE_HOM='GAA' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GAA,
    SUM(CASE WHEN x.VICE_HOM='GLH' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GLH,
    SUM(CASE WHEN x.VICE_HOM='GCT' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GCT,
    SUM(CASE WHEN x.VICE_HOM='GGS' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GGS,
    SUM(CASE WHEN x.VICE_HOM='GOR' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GOR,
    SUM(CASE WHEN x.VICE_HOM='GPA' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GPA,
    SUM(CASE WHEN x.VICE_HOM='GRM' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GRM,
    SUM(CASE WHEN x.VICE_HOM='GTA' AND  CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_GTA
  FROM 
    DIM_DIFERIDAS x
  WHERE 
    SUBSTR(x.EVENT_DATE, 1, 4) IN ('2023', '2024', '2025') AND
    x.CAUSAS_VPU_AGRUPADAS='Operacionales'
  GROUP BY 
    x.CAUSAS_VPU_AGRUPADAS,
    x.CAUSE_NIVEL4,
    x.CAUSE_NIVEL5
),
total_general AS (
  SELECT SUM(BOPD_2023 + BOPD_2024 + BOPD_2025) AS TOTAL FROM datos
),
porcentajes AS (
  SELECT 
    d.CAUSAS_VPU_AGRUPADAS,
    d.CAUSE_NIVEL4,    
    d.CAUSE_NIVEL5,
    d.BOPD_2023,
    d.BOPD_2024,
    d.BOPD_2025,
    d.BOPD_GAA,
    d.BOPD_GLH,
    d.BOPD_GCT,
    d.BOPD_GGS,
    d.BOPD_GOR,
    d.BOPD_GPA,
    d.BOPD_GRM,
    d.BOPD_GTA,
CASE
      WHEN (d.BOPD_2025 - d.BOPD_2024) > 10 THEN 1
      WHEN (d.BOPD_2025 - d.BOPD_2024) < 0 THEN 3
      ELSE 2
    END AS DIFERENCIA,
    ROUND((d.BOPD_2023 + d.BOPD_2024 + d.BOPD_2025) / t.TOTAL, 2) AS PORCENTAJE
  FROM datos d, total_general t
),
agrupado AS (
  SELECT 
    CAUSAS_VPU_AGRUPADAS,
    CAUSE_NIVEL4,    
    CAUSE_NIVEL5,
    ROUND(BOPD_2023, 2) AS BOPD_2023,
    ROUND(BOPD_2024, 2) AS BOPD_2024,
    ROUND(BOPD_2025, 2) AS BOPD_2025,
    ROUND(BOPD_GAA, 2) AS BOPD_GAA,
    ROUND(BOPD_GLH, 2) AS BOPD_GLH,
    ROUND(BOPD_GCT, 2) AS BOPD_GCT,
    ROUND(BOPD_GGS, 2) AS BOPD_GGS,
    ROUND(BOPD_GOR, 2) AS BOPD_GOR,
    ROUND(BOPD_GPA, 2) AS BOPD_GPA,
    ROUND(BOPD_GRM, 2) AS BOPD_GRM,
    ROUND(BOPD_GTA, 2) AS BOPD_GTA,
    DIFERENCIA,
    PORCENTAJE
  FROM porcentajes
  WHERE PORCENTAJE >= 0.01
  UNION ALL
  SELECT 
    CAUSAS_VPU_AGRUPADAS,
    CAUSE_NIVEL4,    
    'otros' AS CAUSE_NIVEL5,
    ROUND(SUM(BOPD_2023), 2),
    ROUND(SUM(BOPD_2024), 2),
    ROUND(SUM(BOPD_2025), 2),
    ROUND(SUM(BOPD_GAA), 2),
    ROUND(SUM(BOPD_GLH), 2),
    ROUND(SUM(BOPD_GCT), 2),
    ROUND(SUM(BOPD_GGS), 2),
    ROUND(SUM(BOPD_GOR), 2),
    ROUND(SUM(BOPD_GPA), 2),
    ROUND(SUM(BOPD_GRM), 2),
    ROUND(SUM(BOPD_GTA), 2),    
    2 AS DIFERENCIA,
    ROUND(SUM(PORCENTAJE), 2)
  FROM porcentajes
  WHERE PORCENTAJE < 0.01
)
SELECT * 
FROM agrupado
ORDER BY 
  CASE WHEN CAUSE_NIVEL5 = 'otros' THEN 'zzz' ELSE CAUSE_NIVEL5 END;

