DROP VIEW IF EXISTS PARETOS_N4_AMBIENTAL_GROUP;
CREATE VIEW PARETOS_N4_AMBIENTAL_GROUP AS WITH datos AS (
  SELECT 
    x.CAUSAS_VPU_AGRUPADAS,
    x.CAUSE_NIVEL4,
    SUM(CASE WHEN CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2023 THEN x.BOPD ELSE 0 END) AS BOPD_2023,
    SUM(CASE WHEN CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2024 THEN x.BOPD ELSE 0 END) AS BOPD_2024,
    SUM(CASE WHEN CAST(SUBSTR(x.EVENT_DATE, 1, 4) AS INTEGER) = 2025 THEN x.ACEITE_PERDIDO ELSE 0 END)  / (SELECT dias FROM DIM_CORTE WHERE anio = 2025) AS BOPD_2025,
